class RobustnessTests(unittest.TestCase):
    """speak_numbers runs at message intake: an exception drops the message."""

    def test_odd_input_does_not_raise(self):
        huge = "1" + " 000" * 11
        for raw in ("100 100 100 100 100 100 100 100 100 100 100 100",
                    huge, huge + "$", huge + "%", huge + "-й", huge + ":1", huge + "/2",
                    "№" + huge, "x" + huge, "1 000 000 000 000 000 000 000 000 000 000к",
                    # re.I folds these old Cyrillic letters into т and с.
                    "5 \N{CYRILLIC SMALL LETTER TALL TE}ыс", "5 ты\N{CYRILLIC SMALL LETTER WIDE ES}",
                    "9" * 5000, "1-" * 1000, "1." * 1000, "1" + ".000" * 1500):
            with self.subTest(raw=raw[:40]):
                self.assertIsInstance(speak_numbers(raw), str)

    def test_a_failure_keeps_the_digits(self):
        with patch("ttsbot.textnorm.speak_numbers", side_effect=KeyError(11)), \
                self.assertLogs("tts_bot", "ERROR"):
            self.assertEqual(normalize_for_tts("у меня 5 минут"), "у меня 5 минут")


class CleanupTests(unittest.TestCase):
    def test_the_spoken_form_has_words_for_numbers(self):
        out = normalize_for_tts("<@1> буду через 5 минут", mentions={"1": "Вася"})
        self.assertEqual(out, "Вася буду через пять минут")
        self.assertEqual(speakable_text("у меня 2 машины"), "у меня две машины")

    def test_the_length_cap_counts_the_words(self):
        self.assertEqual(normalize_for_tts("1000000 раз", max_chars=10), "один")

    def test_tts_numbers_off_keeps_the_digits(self):
        with patch.dict(os.environ, {"TTS_NUMBERS": "off"}):
            config.reload()
        self.addCleanup(config.reload)
        self.assertEqual(normalize_for_tts("у меня 5 минут"), "у меня 5 минут")


class SpeedTests(unittest.TestCase):
    """The owner's budget: under 10 ms for a message (the server is an
    old dual-core laptop CPU); scripts/bench_numerals.py measures more."""

    def _median_seconds(self, text: str, runs: int = 30) -> float:
        times = []
        for _ in range(runs):
            started = time.perf_counter()
            speak_numbers(text)
            times.append(time.perf_counter() - started)
        return statistics.median(times)

    def test_a_long_message_full_of_numbers_takes_under_10_ms(self):
        text = ("с 5 до 7 вечера в 3 играх 21-го числа в 21:00 за 100$ 50% 3,5 часа "
                "2 место 1.5к 30.10.2026 x2 1v1 ") * 3
        self.assertLess(self._median_seconds(text[:300]), 0.010)

    def test_only_what_the_length_cap_keeps_is_spelled_out(self):
        times = []
        for _ in range(10):
            started = time.perf_counter()
            normalize_for_tts("1 " * 2000, max_chars=300)
            times.append(time.perf_counter() - started)
        self.assertLess(statistics.median(times), 0.010)

    def test_a_message_without_digits_costs_next_to_nothing(self):
        self.assertLess(self._median_seconds("привет, как дела? го играть " * 10), 0.0002)


